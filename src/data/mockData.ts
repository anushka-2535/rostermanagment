// Generate comprehensive full-month roster for 32 employees
export function generateSampleRoster(year = 2026, month = 11): RosterCell[] {
  const cells: RosterCell[] = [];
  const daysInMonth = new Date(year, month, 0).getDate();
  const shiftRotation: ShiftType[] = ['MORNING', 'EVENING', 'GENERAL', 'NIGHT'];

  INITIAL_EMPLOYEES.forEach((emp, empIdx) => {
    for (let day = 1; day <= daysInMonth; day++) {
      const dateStr = `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
      const dayOfWeek = new Date(year, month - 1, day).getDay();

      // Check if employee has approved leave
      const hasLeave = INITIAL_LEAVES.some(
        (l) => l.employeeId === emp.id && l.status === 'APPROVED' && dateStr >= l.startDate && dateStr <= l.endDate
      );

      // Check if public holiday
      const holiday = INITIAL_HOLIDAYS.find((h) => h.date === dateStr);

      let shift: ShiftType;
      if (hasLeave) {
        shift = 'LEAVE';
      } else if (emp.fixedWeeklyOffDay !== undefined && dayOfWeek === emp.fixedWeeklyOffDay) {
        shift = 'OFF';
      } else {
        const rotIdx = (empIdx + Math.floor(day / 5)) % shiftRotation.length;
        shift = emp.preferredShift !== 'GENERAL' && day % 3 === 0 
          ? emp.preferredShift 
          : shiftRotation[rotIdx];
      }

      cells.push({
        id: `rc-${emp.id}-${dateStr}`,
        employeeId: emp.id,
        date: dateStr,
        shift: shift,
        brandId: emp.certifiedBrandIds[0],
        processId: emp.certifiedProcessIds[0],
        isLocked: day < 20,
      });
    }
  });

  return cells;
}

